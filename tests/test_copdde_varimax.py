def test_varimax_matches_matlab_rotatefactors():
    for A, L in _reference():
        np.testing.assert_allclose(_varimax(A, q=1000), L, rtol=0, atol=1e-10)


def test_varimax_is_an_orthogonal_rotation():
    for A, _ in _reference():
        L = _varimax(A, q=1000)
        T, *_ = np.linalg.lstsq(A, L, rcond=None)
        np.testing.assert_allclose(T.T @ T, np.eye(A.shape[1]), atol=1e-10)
